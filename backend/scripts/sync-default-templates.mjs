// Generates backend/src/DefaultData.gs from the single source of truth in
// frontend/src/data/defaultTemplates.ts, so both sides seed identical templates.
//   node scripts/sync-default-templates.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import vm from 'node:vm';

const here = dirname(fileURLToPath(import.meta.url));
const source = resolve(here, '../../frontend/src/data/defaultTemplates.ts');
const target = resolve(here, '../src/DefaultData.gs');

export function loadFrontendTemplates() {
  const ts = readFileSync(source, 'utf8');
  const start = ts.indexOf('DEFAULT_TEMPLATES: DefaultTemplate[] = [');
  if (start === -1) throw new Error('DEFAULT_TEMPLATES array not found in ' + source);
  const arrayStart = ts.indexOf('[', ts.indexOf('=', start));
  const arrayEnd = ts.lastIndexOf('];');
  return vm.runInNewContext(`(${ts.slice(arrayStart, arrayEnd + 1)})`);
}

const CATEGORIES = [
  { categoryId: 'DEVOTEE', label: 'Devotee', description: 'Members of the spiritual community', sortOrder: 1 },
  { categoryId: 'GENERAL', label: 'General', description: 'Friends, family and colleagues', sortOrder: 2 },
  { categoryId: 'HELP_DONOR', label: 'Help Donor', description: 'Supporters and donors', sortOrder: 3 },
];

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const templates = loadFrontendTemplates();
  const out = `/**
 * DefaultData.gs — GENERATED by scripts/sync-default-templates.mjs. Do not edit by hand.
 * Source of truth: frontend/src/data/defaultTemplates.ts
 * Seeded by setup(); existing rows (matched by ID) are never overwritten.
 */
const DEFAULT_CATEGORIES = Object.freeze(${JSON.stringify(CATEGORIES, null, 2)});

const DEFAULT_TEMPLATES = Object.freeze(${JSON.stringify(templates, null, 2)});
`;
  writeFileSync(target, out);
  console.log(`Wrote ${templates.length} templates to ${target}`);
}
